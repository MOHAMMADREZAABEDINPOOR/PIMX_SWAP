import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { readFile, mkdir } from 'node:fs/promises';
const en = JSON.parse(await readFile('src/i18n/en.json'));
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1060, height: 790 } });
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
await page.addInitScript(() => {
  window.isTauri=true; window.mockCalls=[];
  let config={uiLanguage:'en',theme:'dark',autoHotkey:'Ctrl+Shift+Space',reverseHotkey:'Ctrl+Alt+Shift+Space',openHotkey:'Ctrl+Alt+P',preferredLayouts:[],source:'en',target:'fa',threshold:.86,launchAtStartup:false,minimizeToTray:true,startMinimized:false,notifications:true,reduceMotion:false,animationIntensity:1,restoreClipboard:true,debugLogs:false,onboarded:false};
  const layouts=[{id:'en',name:'English (United States)',language:'en',active:true},{id:'fa',name:'Persian (Iran)',language:'fa',active:false},{id:'fr',name:'French',language:'fr',active:false},...Array.from({length:200},(_,i)=>({id:`layout-${i}`,name:`Keyboard layout ${i}`,language:'xx',active:false}))];
  window.__TAURI_EVENT_PLUGIN_INTERNALS__={unregisterListener:()=>{}};
  window.__TAURI_INTERNALS__={transformCallback:()=>1,invoke:async(cmd,args)=>{
    window.mockCalls.push({cmd,args});
    if(cmd==='bootstrap') return {config,layouts,paused:false,errors:[],version:'1.0.0',systemLanguage:'en'};
    if(cmd==='save_settings') {config=args.config; return config;}
    if(cmd==='pending_selection')return null;
    if(cmd==='refresh_layouts')return layouts;
    if(cmd==='convert_text')return {text:'hello',mapped:5,unmapped:0};
    if(cmd==='analyze_text')return {action:'apply',candidates:[{text:'hello'}],originalConfidence:0};
    return 1;
  }};
});
try {
  await page.goto('http://127.0.0.1:1420');
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('button',{name:en.next,exact:true}).click();
  await page.getByRole('heading',{name:en.chooseLanguages}).waitFor();
  assert.equal(await page.locator('.onboarding-step').evaluate(e=>getComputedStyle(e).animationName),'step-enter');
  await dialog.getByRole('button',{name:en.target,exact:true}).click();
  await page.getByRole('combobox',{name:en.searchLayouts,exact:true}).fill('french');
  assert.equal(await page.getByRole('option').count(),1);
  await page.screenshot({path:'test-results/layout-search.png'});
  await page.getByRole('combobox',{name:en.searchLayouts,exact:true}).press('Enter');
  assert.match(await dialog.getByRole('button',{name:en.target,exact:true}).innerText(),/French/);
  await dialog.getByRole('button',{name:en.next,exact:true}).click();
  await dialog.getByRole('button',{name:en.getStarted,exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  await page.locator('.toast').waitFor();
  await page.waitForTimeout(5300);
  assert.equal(await page.locator('.toast').count(),0,'Toast disappears after five seconds');
  await page.locator('#input-text').fill('اثممخ');
  await page.locator('.convert-button').click();
  assert.equal(await page.locator('#output-text').inputValue(),'hello');
  await page.getByRole('button',{name:en.compact,exact:true}).click();
  await page.setViewportSize({width:800,height:440});
  assert.equal(await page.locator('.hero').isVisible(),false);
  assert.equal(await page.locator('#input-text').inputValue(),'اثممخ');
  assert.equal(await page.locator('#output-text').inputValue(),'hello');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const convertBox=await page.locator('.convert-button').boundingBox();
  assert.ok(convertBox.y + convertBox.height <= 440, 'Convert button fits compact window');
  await page.screenshot({path:'test-results/compact-workspace.png'});
  await page.getByRole('button',{name:en.direct,exact:true}).click();
  await page.setViewportSize({width:520,height:340});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight), 'Compact direct mode has no page scrollbar');
  const before=await page.locator('.layout-bar').boundingBox();
  await page.getByRole('button',{name:en.source,exact:true}).click();
  const after=await page.locator('.layout-bar').boundingBox();
  assert.ok(Math.abs(after.height-before.height)<1,'Opening language menu preserves panel height');
  await page.getByRole('combobox',{name:en.searchLayouts,exact:true}).press('Escape');
  await page.screenshot({path:'test-results/compact-direct-small.png'});
  await page.getByRole('button',{name:en.expand,exact:true}).click();
  await page.setViewportSize({width:1060,height:790});
  await page.getByRole('button',{name:en.settings,exact:true}).click();
  await page.getByRole('button',{name:en.target,exact:true}).click();
  await page.getByRole('combobox',{name:en.searchLayouts,exact:true}).fill('Persian');
  await page.getByRole('combobox',{name:en.searchLayouts,exact:true}).press('Enter');
  assert.match(await page.getByRole('button',{name:en.target,exact:true}).innerText(),/Persian/);
  await page.getByRole('button',{name:en.converter,exact:true}).click();
  assert.equal(await page.locator('#output-text').inputValue(),'hello');
  assert.deepEqual(errors,[]);
  console.log('Onboarding motion, searchable layouts, keyboard selection, five-second toast and compact workspace passed.');
} finally {await browser.close();}
